CREATE TABLE category (
    cat_uid        integer      GENERATED BY DEFAULT AS IDENTITY,
    cat_parent_uid integer,
    cat_name       varchar(100) NOT NULL,
    cat_slug       varchar(100) NOT NULL,
    CONSTRAINT PK_category         PRIMARY KEY (cat_uid),
    CONSTRAINT UQ_category_slug    UNIQUE (cat_slug),
    CONSTRAINT FK_category_parent  FOREIGN KEY (cat_parent_uid) REFERENCES category (cat_uid) ON DELETE RESTRICT,
    CONSTRAINT CK_category_notself CHECK (cat_parent_uid IS NULL OR cat_parent_uid <> cat_uid),
    CONSTRAINT CK_category_slug    CHECK (cat_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

COMMENT ON TABLE  category                IS 'Категорія робіт. Ієрархія довільної глибини (РЕКУРСИВНИЙ FK)';
COMMENT ON COLUMN category.cat_parent_uid IS 'NULL = корінь дерева; інакше — батьківська категорія';


CREATE TABLE skill (
    sk_uid     integer      GENERATED BY DEFAULT AS IDENTITY,
    sk_cat_uid integer      NOT NULL,
    sk_name    varchar(100) NOT NULL,
    sk_slug    varchar(100) NOT NULL,
    CONSTRAINT PK_skill          PRIMARY KEY (sk_uid),
    CONSTRAINT UQ_skill_slug     UNIQUE (sk_slug),
    CONSTRAINT FK_skill_category FOREIGN KEY (sk_cat_uid) REFERENCES category (cat_uid) ON DELETE RESTRICT,
    CONSTRAINT CK_skill_slug     CHECK (sk_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

COMMENT ON TABLE skill IS 'Навичка всередині категорії';


CREATE TABLE freelancer_skill (
    fs_uid    bigint   GENERATED BY DEFAULT AS IDENTITY,
    fs_fp_uid bigint   NOT NULL,
    fs_sk_uid integer  NOT NULL,
    fs_level  smallint NOT NULL DEFAULT 1,
    fs_years  numeric(4,1),
    CONSTRAINT PK_freelancer_skill      PRIMARY KEY (fs_uid),
    CONSTRAINT UQ_freelancer_skill_pair UNIQUE (fs_fp_uid, fs_sk_uid),
    CONSTRAINT FK_freelancer_skill_fp   FOREIGN KEY (fs_fp_uid) REFERENCES freelancer_profile (fp_uid) ON DELETE CASCADE,
    CONSTRAINT FK_freelancer_skill_sk   FOREIGN KEY (fs_sk_uid) REFERENCES skill (sk_uid)              ON DELETE CASCADE,
    CONSTRAINT CK_freelancer_skill_lvl  CHECK (fs_level BETWEEN 1 AND 5)
);

COMMENT ON TABLE  freelancer_skill          IS 'M:N між freelancer_profile і skill. Розв''язна таблиця з атрибутами';
COMMENT ON COLUMN freelancer_skill.fs_level IS 'Рівень володіння навичкою, 1..5';


-- ============================================================================
--  МОДУЛЬ 4. ЗАМОВЛЕННЯ
-- ============================================================================

CREATE TABLE project (
    p_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    p_cp_uid       bigint        NOT NULL,
    p_cat_uid      integer,
    p_title        varchar(200)  NOT NULL,
    p_description  text          NOT NULL,
    p_pricing_type varchar(8)    NOT NULL,
    p_budget_min   numeric(14,2),
    p_budget_max   numeric(14,2),
    p_currency_uid smallint      NOT NULL,
    p_status       varchar(16)   NOT NULL DEFAULT 'OPEN',
    p_deadline     date,
    p_created_at   timestamptz   NOT NULL DEFAULT now(),
    p_updated_at   timestamptz,
    p_updated_by   bigint,
    p_is_deleted   boolean       NOT NULL DEFAULT false,
    p_deleted_at   timestamptz,
    CONSTRAINT PK_project         PRIMARY KEY (p_uid),
    CONSTRAINT FK_project_client  FOREIGN KEY (p_cp_uid)       REFERENCES client_profile (cp_uid) ON DELETE RESTRICT,
    CONSTRAINT FK_project_category FOREIGN KEY (p_cat_uid)     REFERENCES category (cat_uid)       ON DELETE SET NULL,
    CONSTRAINT FK_project_currency FOREIGN KEY (p_currency_uid) REFERENCES currency (cur_uid)      ON DELETE RESTRICT,
    CONSTRAINT FK_project_upd_by  FOREIGN KEY (p_updated_by)   REFERENCES app_user (u_uid)         ON DELETE SET NULL,
    CONSTRAINT CK_project_pricing CHECK (p_pricing_type IN ('FIXED', 'HOURLY')),
    CONSTRAINT CK_project_status  CHECK (p_status IN ('DRAFT', 'OPEN', 'IN_PROGRESS', 'CLOSED', 'CANCELLED')),
    CONSTRAINT CK_project_budget  CHECK (p_budget_min IS NULL OR p_budget_min >= 0),
    CONSTRAINT CK_project_range   CHECK (p_budget_min IS NULL OR p_budget_max IS NULL
                                      OR p_budget_max >= p_budget_min),
    CONSTRAINT CK_project_softdel CHECK ((p_is_deleted = false AND p_deleted_at IS NULL)
                                      OR (p_is_deleted = true  AND p_deleted_at IS NOT NULL))
);

COMMENT ON TABLE  project               IS 'Замовлення, опубліковане замовником. Soft delete + аудит';
COMMENT ON COLUMN project.p_pricing_type IS 'FIXED — фіксована ціна; HOURLY — погодинна оплата';


CREATE TABLE proposal (
    pr_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    pr_p_uid        bigint        NOT NULL,
    pr_fp_uid       bigint        NOT NULL,
    pr_cover_letter text          NOT NULL,
    pr_bid_amount   numeric(14,2) NOT NULL,
    pr_currency_uid smallint      NOT NULL,
    pr_days         smallint,
    pr_status       varchar(16)   NOT NULL DEFAULT 'SENT',
    pr_created_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT PK_proposal          PRIMARY KEY (pr_uid),
    CONSTRAINT UQ_proposal_pair     UNIQUE (pr_p_uid, pr_fp_uid),
    CONSTRAINT FK_proposal_project  FOREIGN KEY (pr_p_uid)        REFERENCES project (p_uid)             ON DELETE CASCADE,
    CONSTRAINT FK_proposal_free     FOREIGN KEY (pr_fp_uid)       REFERENCES freelancer_profile (fp_uid) ON DELETE RESTRICT,
    CONSTRAINT FK_proposal_currency FOREIGN KEY (pr_currency_uid) REFERENCES currency (cur_uid)          ON DELETE RESTRICT,
    CONSTRAINT CK_proposal_status   CHECK (pr_status IN ('SENT', 'VIEWED', 'ACCEPTED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT CK_proposal_amount   CHECK (pr_bid_amount > 0)
);

COMMENT ON TABLE proposal IS 'Відгук фрілансера на замовлення. Один фрілансер — один відгук на проєкт';


-- Аудит: контракт — головний транзакційний документ, важливо знати,
-- хто востаннє його чіпав.
CREATE TABLE contract (
    ct_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    ct_pr_uid       bigint        NOT NULL,
    ct_p_uid        bigint        NOT NULL,
    ct_cp_uid       bigint        NOT NULL,
    ct_fp_uid       bigint        NOT NULL,
    ct_amount       numeric(14,2) NOT NULL,
    ct_currency_uid smallint      NOT NULL,
    ct_start_date   date          NOT NULL,
    ct_end_date     date,
    ct_status       varchar(16)   NOT NULL DEFAULT 'ACTIVE',
    ct_created_at   timestamptz   NOT NULL DEFAULT now(),
    ct_updated_at   timestamptz,
    ct_updated_by   bigint,
    CONSTRAINT PK_contract          PRIMARY KEY (ct_uid),
    CONSTRAINT UQ_contract_proposal UNIQUE (ct_pr_uid),
    CONSTRAINT FK_contract_proposal FOREIGN KEY (ct_pr_uid)       REFERENCES proposal (pr_uid)           ON DELETE RESTRICT,
    CONSTRAINT FK_contract_project  FOREIGN KEY (ct_p_uid)        REFERENCES project (p_uid)             ON DELETE RESTRICT,
    CONSTRAINT FK_contract_client   FOREIGN KEY (ct_cp_uid)       REFERENCES client_profile (cp_uid)     ON DELETE RESTRICT,
    CONSTRAINT FK_contract_free     FOREIGN KEY (ct_fp_uid)       REFERENCES freelancer_profile (fp_uid) ON DELETE RESTRICT,
    CONSTRAINT FK_contract_currency FOREIGN KEY (ct_currency_uid) REFERENCES currency (cur_uid)          ON DELETE RESTRICT,
    CONSTRAINT FK_contract_upd_by   FOREIGN KEY (ct_updated_by)   REFERENCES app_user (u_uid)            ON DELETE SET NULL,
    CONSTRAINT CK_contract_status   CHECK (ct_status IN ('ACTIVE', 'FINISHED', 'TERMINATED', 'DISPUTED')),
    CONSTRAINT CK_contract_amount   CHECK (ct_amount >= 0),
    CONSTRAINT CK_contract_dates    CHECK (ct_end_date IS NULL OR ct_end_date >= ct_start_date)
);

COMMENT ON TABLE  contract         IS 'Укладений контракт. Зв''язок 1:1 з прийнятим proposal. Аудит';
COMMENT ON COLUMN contract.ct_p_uid IS 'Денормалізація заради швидкодії: виводиться з proposal, але зберігається явно';


-- ============================================================================
--  МОДУЛЬ 5. ВИКОНАННЯ РОБІТ
