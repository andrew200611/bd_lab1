CREATE TABLE invoice (
    inv_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    inv_ct_uid       bigint        NOT NULL,
    inv_number       varchar(32)   NOT NULL,
    inv_amount       numeric(14,2) NOT NULL,
    inv_currency_uid smallint      NOT NULL,
    inv_issued_at    timestamptz   NOT NULL DEFAULT now(),
    inv_due_at       date,
    inv_status       varchar(16)   NOT NULL DEFAULT 'ISSUED',
    CONSTRAINT PK_invoice          PRIMARY KEY (inv_uid),
    CONSTRAINT UQ_invoice_number   UNIQUE (inv_number),
    CONSTRAINT FK_invoice_contract FOREIGN KEY (inv_ct_uid)       REFERENCES contract (ct_uid)  ON DELETE RESTRICT,
    CONSTRAINT FK_invoice_currency FOREIGN KEY (inv_currency_uid) REFERENCES currency (cur_uid) ON DELETE RESTRICT,
    CONSTRAINT CK_invoice_status   CHECK (inv_status IN ('ISSUED', 'PAID', 'OVERDUE', 'CANCELLED')),
    CONSTRAINT CK_invoice_amount   CHECK (inv_amount > 0)
);

COMMENT ON TABLE  invoice            IS 'Рахунок за контрактом';
COMMENT ON COLUMN invoice.inv_number IS 'ПРИРОДНИЙ (бізнесовий) ключ — на відміну від сурогатного inv_uid';


-- Платіж — фінансовий регістр: рядки не редагуються й не видаляються.
-- Це забезпечує тригер trg_payment_immutable (див. 07_triggers.sql).
CREATE TABLE payment (
    pay_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    pay_inv_uid      bigint        NOT NULL,
    pay_amount       numeric(14,2) NOT NULL,
    pay_currency_uid smallint      NOT NULL,
    pay_method       varchar(24)   NOT NULL,
    pay_status       varchar(16)   NOT NULL DEFAULT 'PENDING',
    pay_paid_at      timestamptz,
    pay_external_ref varchar(64),
    CONSTRAINT PK_payment          PRIMARY KEY (pay_uid),
    CONSTRAINT FK_payment_invoice  FOREIGN KEY (pay_inv_uid)      REFERENCES invoice (inv_uid)  ON DELETE RESTRICT,
    CONSTRAINT FK_payment_currency FOREIGN KEY (pay_currency_uid) REFERENCES currency (cur_uid) ON DELETE RESTRICT,
    CONSTRAINT CK_payment_method   CHECK (pay_method IN ('CARD', 'BANK', 'WALLET', 'CRYPTO')),
    CONSTRAINT CK_payment_status   CHECK (pay_status IN ('PENDING', 'COMPLETED', 'FAILED', 'REFUNDED')),
    CONSTRAINT CK_payment_amount   CHECK (pay_amount > 0),
    CONSTRAINT CK_payment_paid     CHECK ((pay_status = 'COMPLETED' AND pay_paid_at IS NOT NULL)
                                       OR (pay_status <> 'COMPLETED'))
);

COMMENT ON TABLE payment IS 'Платіж за рахунком. Фінансовий регістр: UPDATE/DELETE заборонено тригером';


-- ============================================================================
--  МОДУЛЬ 7. КОМУНІКАЦІЯ
-- ============================================================================

CREATE TABLE chat_thread (
    cht_uid        bigint      GENERATED BY DEFAULT AS IDENTITY,
    cht_p_uid      bigint,
    cht_ct_uid     bigint,
    cht_created_at timestamptz NOT NULL DEFAULT now(),
    cht_is_closed  boolean     NOT NULL DEFAULT false,
    CONSTRAINT PK_chat_thread       PRIMARY KEY (cht_uid),
    CONSTRAINT FK_chat_thread_prj   FOREIGN KEY (cht_p_uid)  REFERENCES project (p_uid)   ON DELETE CASCADE,
    CONSTRAINT FK_chat_thread_ctr   FOREIGN KEY (cht_ct_uid) REFERENCES contract (ct_uid) ON DELETE CASCADE,
    CONSTRAINT CK_chat_thread_owner CHECK ((cht_p_uid IS NOT NULL) <> (cht_ct_uid IS NOT NULL))
);

COMMENT ON TABLE  chat_thread             IS 'Тред обговорення: рівно одне з полів cht_p_uid / cht_ct_uid заповнене';
COMMENT ON CONSTRAINT CK_chat_thread_owner ON chat_thread IS 'XOR: тред належить або проєкту, або контракту';


CREATE TABLE message (
    msg_uid     bigint      GENERATED BY DEFAULT AS IDENTITY,
    msg_cht_uid bigint      NOT NULL,
    msg_u_uid   bigint      NOT NULL,
    msg_body    text        NOT NULL,
    msg_sent_at timestamptz NOT NULL DEFAULT now(),
    msg_read_at timestamptz,
    CONSTRAINT PK_message        PRIMARY KEY (msg_uid),
    CONSTRAINT FK_message_thread FOREIGN KEY (msg_cht_uid) REFERENCES chat_thread (cht_uid) ON DELETE CASCADE,
    CONSTRAINT FK_message_author FOREIGN KEY (msg_u_uid)   REFERENCES app_user (u_uid)      ON DELETE RESTRICT,
    CONSTRAINT CK_message_body   CHECK (length(btrim(msg_body)) > 0),
    CONSTRAINT CK_message_read   CHECK (msg_read_at IS NULL OR msg_read_at >= msg_sent_at)
);

COMMENT ON TABLE message IS 'Повідомлення в треді';


-- ============================================================================
--  МОДУЛЬ 8. РЕПУТАЦІЯ
