CREATE TABLE review (
    rv_uid           bigint      GENERATED BY DEFAULT AS IDENTITY,
    rv_ct_uid        bigint      NOT NULL,
    rv_author_u_uid  bigint      NOT NULL,
    rv_target_u_uid  bigint      NOT NULL,
    rv_score         smallint    NOT NULL,
    rv_comment       text,
    rv_created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT PK_review          PRIMARY KEY (rv_uid),
    CONSTRAINT UQ_review_pair     UNIQUE (rv_ct_uid, rv_author_u_uid),
