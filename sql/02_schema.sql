CREATE TABLE milestone (
    ms_uid        bigint        GENERATED BY DEFAULT AS IDENTITY,
    ms_ct_uid     bigint        NOT NULL,
    ms_title      varchar(200)  NOT NULL,
    ms_amount     numeric(14,2) NOT NULL,
    ms_due_date   date,
    ms_status     varchar(16)   NOT NULL DEFAULT 'PENDING',
    ms_created_at timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT PK_milestone          PRIMARY KEY (ms_uid),
    CONSTRAINT FK_milestone_contract FOREIGN KEY (ms_ct_uid) REFERENCES contract (ct_uid) ON DELETE CASCADE,
    CONSTRAINT CK_milestone_status   CHECK (ms_status IN ('PENDING', 'IN_PROGRESS', 'DONE', 'PAID')),
    CONSTRAINT CK_milestone_amount   CHECK (ms_amount > 0)
);

COMMENT ON TABLE milestone IS 'Етап контракту з власною сумою та дедлайном';


CREATE TABLE task (
    t_uid             bigint       GENERATED BY DEFAULT AS IDENTITY,
    t_ms_uid          bigint       NOT NULL,
    t_fp_uid          bigint,
    t_title           varchar(200) NOT NULL,
    t_description     text,
    t_status          varchar(16)  NOT NULL DEFAULT 'TODO',
    t_hours_estimated numeric(6,2),
    t_due_date        date,
    t_created_at      timestamptz  NOT NULL DEFAULT now(),
    t_updated_at      timestamptz,
    t_updated_by      bigint,
    t_is_deleted      boolean      NOT NULL DEFAULT false,
    t_deleted_at      timestamptz,
    CONSTRAINT PK_task            PRIMARY KEY (t_uid),
    CONSTRAINT FK_task_milestone  FOREIGN KEY (t_ms_uid)     REFERENCES milestone (ms_uid)          ON DELETE CASCADE,
    CONSTRAINT FK_task_freelancer FOREIGN KEY (t_fp_uid)     REFERENCES freelancer_profile (fp_uid) ON DELETE SET NULL,
    CONSTRAINT FK_task_upd_by     FOREIGN KEY (t_updated_by) REFERENCES app_user (u_uid)            ON DELETE SET NULL,
    CONSTRAINT CK_task_status     CHECK (t_status IN ('TODO', 'DOING', 'REVIEW', 'DONE')),
    CONSTRAINT CK_task_hours      CHECK (t_hours_estimated IS NULL OR t_hours_estimated > 0),
    CONSTRAINT CK_task_softdel    CHECK ((t_is_deleted = false AND t_deleted_at IS NULL)
                                      OR (t_is_deleted = true  AND t_deleted_at IS NOT NULL))
);

COMMENT ON TABLE task IS 'Задача в межах етапу. Soft delete + аудит';


