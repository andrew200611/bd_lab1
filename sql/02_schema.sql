-- ============================================================================
--  МОДУЛЬ 1. ІДЕНТИЧНІСТЬ І ДОСТУП
-- ============================================================================

CREATE TABLE role (
    r_uid         smallint     GENERATED BY DEFAULT AS IDENTITY,
    r_code        varchar(32)  NOT NULL,
    r_name        varchar(64)  NOT NULL,
    r_description varchar(255),
    CONSTRAINT PK_role      PRIMARY KEY (r_uid),
    CONSTRAINT UQ_role_code UNIQUE (r_code),
    CONSTRAINT CK_role_code CHECK (r_code = upper(r_code))
);

COMMENT ON TABLE role IS 'Довідник ролей користувачів';


-- Soft delete + аудит: акаунт не можна видаляти фізично, бо на нього
-- посилається вся історія платформи.
CREATE TABLE app_user (
    u_uid           bigint       GENERATED BY DEFAULT AS IDENTITY,
    u_email         varchar(255) NOT NULL,
    u_password_hash varchar(255) NOT NULL,
    u_role_uid      smallint     NOT NULL,
    u_status        varchar(16)  NOT NULL DEFAULT 'ACTIVE',
    u_created_at    timestamptz  NOT NULL DEFAULT now(),
    u_updated_at    timestamptz,
    u_updated_by    bigint,
    u_is_deleted    boolean      NOT NULL DEFAULT false,
    u_deleted_at    timestamptz,
    CONSTRAINT PK_app_user         PRIMARY KEY (u_uid),
    CONSTRAINT UQ_app_user_email   UNIQUE (u_email),
    CONSTRAINT FK_app_user_role    FOREIGN KEY (u_role_uid)   REFERENCES role (r_uid)     ON DELETE RESTRICT,
    CONSTRAINT FK_app_user_upd_by  FOREIGN KEY (u_updated_by) REFERENCES app_user (u_uid) ON DELETE SET NULL,
    CONSTRAINT CK_app_user_status  CHECK (u_status IN ('ACTIVE', 'BLOCKED', 'PENDING')),
    CONSTRAINT CK_app_user_email   CHECK (u_email LIKE '%_@_%._%'),
    CONSTRAINT CK_app_user_softdel CHECK ((u_is_deleted = false AND u_deleted_at IS NULL)
                                       OR (u_is_deleted = true  AND u_deleted_at IS NOT NULL)),
    CONSTRAINT CK_app_user_audit   CHECK (u_updated_at IS NULL OR u_updated_at >= u_created_at)
);

COMMENT ON TABLE  app_user             IS 'Акаунт користувача. Soft delete + аудит змін';
COMMENT ON COLUMN app_user.u_is_deleted IS 'SOFT DELETE: фізичного DELETE не робимо, лише позначаємо';


-- ============================================================================
--  МОДУЛЬ 2. ПРОФІЛІ ТА ДОВІДНИКИ
-- ============================================================================

CREATE TABLE country (
    c_uid  smallint     GENERATED BY DEFAULT AS IDENTITY,
    c_iso2 char(2)      NOT NULL,
    c_iso3 char(3)      NOT NULL,
    c_name varchar(100) NOT NULL,
    CONSTRAINT PK_country      PRIMARY KEY (c_uid),
    CONSTRAINT UQ_country_iso2 UNIQUE (c_iso2),
    CONSTRAINT UQ_country_iso3 UNIQUE (c_iso3),
    CONSTRAINT CK_country_iso2 CHECK (c_iso2 ~ '^[A-Z]{2}$'),
    CONSTRAINT CK_country_iso3 CHECK (c_iso3 ~ '^[A-Z]{3}$')
);

COMMENT ON TABLE country IS 'Довідник країн (ISO 3166-1)';


CREATE TABLE currency (
    cur_uid      smallint    GENERATED BY DEFAULT AS IDENTITY,
    cur_iso_code char(3)     NOT NULL,
    cur_name     varchar(64) NOT NULL,
    cur_symbol   varchar(8),
    CONSTRAINT PK_currency     PRIMARY KEY (cur_uid),
    CONSTRAINT UQ_currency_iso UNIQUE (cur_iso_code),
    CONSTRAINT CK_currency_iso CHECK (cur_iso_code ~ '^[A-Z]{3}$')
);

COMMENT ON TABLE currency IS 'Довідник валют (ISO 4217)';


CREATE TABLE client_profile (
    cp_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    cp_u_uid        bigint        NOT NULL,
    cp_company_name varchar(150),
    cp_country_uid  smallint,
    cp_currency_uid smallint,
    cp_balance      numeric(14,2) NOT NULL DEFAULT 0,
    cp_rating_avg   numeric(3,2),
    cp_created_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT PK_client_profile          PRIMARY KEY (cp_uid),
    CONSTRAINT UQ_client_profile_user     UNIQUE (cp_u_uid),
    CONSTRAINT FK_client_profile_user     FOREIGN KEY (cp_u_uid)        REFERENCES app_user (u_uid) ON DELETE CASCADE,
    CONSTRAINT FK_client_profile_country  FOREIGN KEY (cp_country_uid)  REFERENCES country (c_uid)  ON DELETE SET NULL,
    CONSTRAINT FK_client_profile_currency FOREIGN KEY (cp_currency_uid) REFERENCES currency (cur_uid) ON DELETE SET NULL,
    CONSTRAINT CK_client_profile_balance  CHECK (cp_balance >= 0),
    CONSTRAINT CK_client_profile_rating   CHECK (cp_rating_avg IS NULL OR cp_rating_avg BETWEEN 0 AND 5)
);

COMMENT ON TABLE client_profile IS 'Профіль замовника. Зв''язок 1:1 з app_user (через UNIQUE)';


CREATE TABLE freelancer_profile (
    fp_uid          bigint        GENERATED BY DEFAULT AS IDENTITY,
    fp_u_uid        bigint        NOT NULL,
    fp_title        varchar(150),
    fp_bio          text,
    fp_hourly_rate  numeric(10,2),
    fp_currency_uid smallint,
    fp_country_uid  smallint,
    fp_rating_avg   numeric(3,2),
    fp_is_available boolean       NOT NULL DEFAULT true,
    fp_created_at   timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT PK_freelancer_profile          PRIMARY KEY (fp_uid),
    CONSTRAINT UQ_freelancer_profile_user     UNIQUE (fp_u_uid),
    CONSTRAINT FK_freelancer_profile_user     FOREIGN KEY (fp_u_uid)        REFERENCES app_user (u_uid) ON DELETE CASCADE,
    CONSTRAINT FK_freelancer_profile_country  FOREIGN KEY (fp_country_uid)  REFERENCES country (c_uid)  ON DELETE SET NULL,
    CONSTRAINT FK_freelancer_profile_currency FOREIGN KEY (fp_currency_uid) REFERENCES currency (cur_uid) ON DELETE SET NULL,
    CONSTRAINT CK_freelancer_profile_rate     CHECK (fp_hourly_rate IS NULL OR fp_hourly_rate >= 0),
    CONSTRAINT CK_freelancer_profile_rating   CHECK (fp_rating_avg IS NULL OR fp_rating_avg BETWEEN 0 AND 5)
);

COMMENT ON TABLE freelancer_profile IS 'Профіль фрілансера. Зв''язок 1:1 з app_user';


-- ============================================================================
--  МОДУЛЬ 3. КОМПЕТЕНЦІЇ
