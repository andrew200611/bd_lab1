--  СТАНДАРТ ІМЕНУВАННЯ (лекція 2, слайд 9):
--    таблиця              — іменник в однині, snake_case, англійською
--    сурогатний PK        — <abbr>_uid
--    обмеження PK         — PK_<table>
--    обмеження UNIQUE     — UQ_<table>_<cols>
--    обмеження FOREIGN KEY— FK_<table>_<ref>
--    обмеження CHECK      — CK_<table>_<what>
--    колонка FK           — <abbr>_<ref_abbr>_uid
--
--  П.3 завдання — «частина сутностей soft delete, частина — дата зміни».
--  Тому ці колонки стоять НЕ всюди, а лише там, де це має сенс:
--    soft delete — app_user, project, task
--    аудит       — app_user, project, contract
