-- ============================================================================
--  Крок 6 (п.6 завдання): ІНДЕКСИ
--  Запуск:  psql -d freelancer_platform -f sql/08_indexes.sql
-- ----------------------------------------------------------------------------
--  Завдання вимагає «щонайменше два різних типи» індексів. Тут їх чотири,
--  і кожен обраний під конкретний характер запиту, а не «щоб було»:
--
--    B-tree         — рівність і діапазони, сортування. Типовий вибір.
--    B-tree partial — індекс лише по частині рядків (WHERE p_is_deleted = false).
--                     Менший розмір -> швидший пошук і дешевше оновлення.
--    GIN            — повнотекстовий пошук. Для «багато значень в одному
--                     рядку» B-tree непридатний.
--    BRIN           — великі таблиці з фізичним порядком за часом.
--                     Крихітний розмір.
--    Hash           — лише точна рівність, зате компактніший за B-tree.
--
--  Індекси не безкоштовні: кожен сповільнює INSERT/UPDATE і займає місце.
--  Тому нижче на кожен індекс є обґрунтування — під який саме запит.
-- ============================================================================

SET search_path TO public;


-- ===========================================================================
--  1. B-tree складений: стрічка замовлень у кабінеті
-- ===========================================================================
--  Запит: «показати відкриті замовлення, найближчі дедлайни — першими».
--  Порядок колонок важливий: спершу рівність (p_status), потім сортування
--  (p_deadline). Якби навпаки — індекс не давав би готового порядку.
-- ===========================================================================
CREATE INDEX IF NOT EXISTS IX_project_status_deadline
    ON project (p_status, p_deadline);

COMMENT ON INDEX IX_project_status_deadline IS
    'Стрічка замовлень: фільтр за статусом + сортування за дедлайном';


-- ===========================================================================
--  2. B-tree частковий: активні замовлення замовника
-- ===========================================================================
--  Майже всі запити застосунку дивляться лише на невидалені рядки.
--  Частковий індекс містить тільки їх — він помітно менший за повний.
-- ===========================================================================
CREATE INDEX IF NOT EXISTS IX_project_active_client
    ON project (p_cp_uid, p_created_at DESC)
    WHERE p_is_deleted = false;

COMMENT ON INDEX IX_project_active_client IS
    'Частковий: лише активні (не видалені) замовлення конкретного замовника';


-- ===========================================================================
--  3. GIN: повнотекстовий пошук по замовленнях
-- ===========================================================================
--  Обслуговує пошук по назві й опису замовлення (сторінка «Знайти роботу»).
--  Конфігурація 'simple': українського стемера в PostgreSQL немає, а 'simple'
--  лише нормалізує регістр — зате поводиться передбачувано.
--
--  ВАЖЛИВО: одноаргументний to_tsvector(text) — це STABLE-функція, а STABLE
--  індексувати не можна. Потрібен дворгументний виклик із літералом
--  'simple', який є IMMUTABLE. І вираз у запиті мусить бути символ-у-символ
--  таким самим, інакше планер індекс не побачить.
-- ===========================================================================
CREATE INDEX IF NOT EXISTS IX_project_fts
    ON project
    USING gin (to_tsvector('simple', p_title || ' ' || p_description))
    WHERE p_is_deleted = false;

COMMENT ON INDEX IX_project_fts IS
    'GIN: повнотекстовий пошук по назві й опису замовлення (FTS, simple)';


-- ===========================================================================
--  4. BRIN: часова вісь переписки
-- ===========================================================================
--  message — таблиця, яку лише дописують: рядки фізично впорядковані за
--  часом, бо uid видається послідовністю. Саме для таких таблиць існує BRIN:
--  він зберігає min/max на кожен блок, тому займає в сотні разів менше місця
--  за B-tree, а для діапазону дат працює майже так само добре.
-- ===========================================================================
CREATE INDEX IF NOT EXISTS IX_message_sent_brin
    ON message
    USING brin (msg_sent_at);

COMMENT ON INDEX IX_message_sent_brin IS
    'BRIN: діапазони за часом у переписці; мінімальний розмір';


-- ===========================================================================
--  5. Hash: пошук платежу за ідентифікатором у платіжній системі
-- ===========================================================================
--  Зовнішній ідентифікатор транзакції шукають лише точно (==). Діапазони й
--  сортування не потрібні, тому B-tree тут надлишковий: Hash компактніший.
--  Сценарій — ідемпотентність вебхуків платіжної системи.
-- ===========================================================================
CREATE INDEX IF NOT EXISTS IX_payment_external_ref_hash
    ON payment
    USING hash (pay_external_ref);

COMMENT ON INDEX IX_payment_external_ref_hash IS
    'Hash: точний пошук платежу за ідентифікатором у зовнішній системі';


\echo '  -> 5 індексів створено (B-tree, partial, GIN, BRIN, Hash)'
